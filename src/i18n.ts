// Tiny i18n: English source strings are the keys; other languages map them.
// Missing translations fall back to English, so nothing ever shows a raw key.

let dict: Record<string, string> = {};
let patterns: [RegExp, string][] = [];

export function initI18n(setting: string) {
  const lang = setting === "auto" ? (navigator.language || "en").slice(0, 2).toLowerCase() : setting;
  dict = lang === "de" ? DE : {};
  patterns = lang === "de" ? DE_BACKEND : [];
  document.documentElement.lang = lang === "de" ? "de" : "en";
}

/** Translate and substitute {0}, {1}, ... */
export function t(text: string, ...args: string[]): string {
  const s = dict[text] ?? text;
  return args.length ? s.replace(/\{(\d)\}/g, (m, i) => args[Number(i)] ?? m) : s;
}

/** Translate a message produced by the Rust backend (status lines, errors, prompts). */
export function tb(message: string): string {
  for (const [re, repl] of patterns) {
    if (re.test(message)) return message.replace(re, repl);
  }
  return message;
}

